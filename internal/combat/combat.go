// Package combat holds the pure combat formulas: character stats, damage and
// EXP. It has no state and no dependency beyond the standard library.
package combat

import (
	"math"
	"time"
)

// Default slash and level constants (spec 3.3, 3.4).
const (
	SlashRange     = 1.5                    // tiles, centre to centre
	SlashCooldown  = 800 * time.Millisecond // no MP cost
	SlashWindup    = 150 * time.Millisecond // from the press to the slash landing
	MaxLevel       = 90
	PointsPerLevel = 10
)

// Points are the potential points a character has spent.
type Points struct{ Str, Agi, Vit, Int int }

// Total is the number of points spent.
func (p Points) Total() int { return p.Str + p.Agi + p.Vit + p.Int }

// Stats are the derived character stats.
type Stats struct {
	MaxHP, MaxMP              int
	PhysAttack, MagicAttack   int
	PhysDefense, MagicDefense int
	Accuracy, Evasion         int
	CritRateBP                int // basis points (1/10000)
}

// Bonus is the summed stats of worn gear (phase 3a spec 4.2).
type Bonus struct {
	HP, PhysAttack, MagicAttack, PhysDefense, MagicDefense int
}

// Add returns the field-wise sum of two bonuses.
func (b Bonus) Add(c Bonus) Bonus {
	return Bonus{
		HP:           b.HP + c.HP,
		PhysAttack:   b.PhysAttack + c.PhysAttack,
		MagicAttack:  b.MagicAttack + c.MagicAttack,
		PhysDefense:  b.PhysDefense + c.PhysDefense,
		MagicDefense: b.MagicDefense + c.MagicDefense,
	}
}

// Compute derives stats from level and spent points (game-design 2.2, spec 3.1).
// magic selects the magic-class HP growth (a = 50, b = 16) instead of the
// physical one (a = 60, b = 20). The gear bonus is added flat to the base
// stats, then passive bonuses apply to that sum (phase 2 spec 3.2, phase 3a
// spec 4.2).
func Compute(magic bool, level int, p Points, gear Bonus, pas Passive) Stats {
	l := level - 1
	hpA, hpB := 60, 20
	if magic {
		hpA, hpB = 50, 16
	}
	def := 10 + 2*l + 2*p.Vit
	st := Stats{
		MaxHP:        500 + hpA*l + hpB*p.Vit,
		MaxMP:        100 + 20*l + 5*p.Int,
		PhysAttack:   20 + 5*l + 2*p.Str,
		MagicAttack:  20 + 5*l + 2*p.Int,
		PhysDefense:  def,
		MagicDefense: def,
		Accuracy:     100 + 5*l + 3*p.Agi,
		Evasion:      50 + 5*l + 2*p.Agi,
		CritRateBP:   500 + 2*p.Agi,
	}
	st.MaxHP += gear.HP
	st.PhysAttack += gear.PhysAttack
	st.MagicAttack += gear.MagicAttack
	st.PhysDefense += gear.PhysDefense
	st.MagicDefense += gear.MagicDefense
	st.MaxHP += st.MaxHP * pas.MaxHPPct / 100
	st.MagicAttack += st.MagicAttack * pas.MagicAttackPct / 100
	st.PhysDefense += st.PhysDefense * pas.PhysDefPct / 100
	st.MagicDefense += st.MagicDefense * pas.MagicDefPct / 100
	st.Accuracy += st.Accuracy * pas.AccuracyPct / 100
	st.Evasion += st.Evasion * pas.EvasionPct / 100
	st.CritRateBP += pas.CritBP
	return st
}

// Damage is max(1, floor(base * (1 - def / (def + 20 * attackerLevel))))
// (spec 3.2). Hits always land and never crit.
func Damage(base, defense, attackerLevel int) int {
	d, k := float64(defense), 20*float64(attackerLevel)
	got := int(math.Floor(float64(base) * (1 - d/(d+k))))
	if got < 1 {
		return 1
	}
	return got
}

// RangedFactor scales a monster's ranged shot against its melee hit
// (monster regions spec 3.1).
const RangedFactor = 0.5

// MonsterRangedDamage is max(1, floor(Damage * RangedFactor)). Shots always
// land and never crit.
func MonsterRangedDamage(base, defense, attackerLevel int) int {
	got := int(math.Floor(float64(Damage(base, defense, attackerLevel)) * RangedFactor))
	if got < 1 {
		return 1
	}
	return got
}

// Passive is the summed effect of learned passive skills (phase 2 spec 3.2).
// Percent fields raise their stat by floor(stat * pct / 100); CritBP is added
// to the crit rate in basis points.
type Passive struct {
	PhysDefPct, MagicDefPct, MaxHPPct, EvasionPct, AccuracyPct, MagicAttackPct int
	CritBP                                                                     int
}

// Add returns the field-wise sum of two passives.
func (p Passive) Add(q Passive) Passive {
	return Passive{
		PhysDefPct:     p.PhysDefPct + q.PhysDefPct,
		MagicDefPct:    p.MagicDefPct + q.MagicDefPct,
		MaxHPPct:       p.MaxHPPct + q.MaxHPPct,
		EvasionPct:     p.EvasionPct + q.EvasionPct,
		AccuracyPct:    p.AccuracyPct + q.AccuracyPct,
		MagicAttackPct: p.MagicAttackPct + q.MagicAttackPct,
		CritBP:         p.CritBP + q.CritBP,
	}
}

// SkillBase is floor(attack * coefPct / 100), using magic attack for magic
// skills and physical attack otherwise (phase 2 spec 3.2).
func SkillBase(s Stats, magic bool, coefPct int) int {
	atk := s.PhysAttack
	if magic {
		atk = s.MagicAttack
	}
	return atk * coefPct / 100
}

// SlashBase is the base damage of the default slash: the higher attack stat
// (spec 3.2, 3.3).
func SlashBase(s Stats) int { return max(s.PhysAttack, s.MagicAttack) }

// ExpTable is the EXP needed to leave each level, index 0 = level 1. It is
// data/exp.json, generated by docs/balance/exp_table.py from monster EXP
// (phase 2 spec 2.4).
type ExpTable []int64

// ToNext is the EXP needed to go from level to level+1. It is 0 at MaxLevel
// and for a level the table does not cover.
func (t ExpTable) ToNext(level int) int64 {
	if level < 1 || level >= MaxLevel || level > len(t) {
		return 0
	}
	return t[level-1]
}

// Gain adds gain to the EXP of the current level. The remainder carries over,
// several levels can be gained at once, and the result stops at MaxLevel with
// exp 0. At MaxLevel nothing is gained. A level the table does not cover
// keeps the EXP and stays where it is.
func (t ExpTable) Gain(level int, exp, gain int64) (newLevel int, newExp int64) {
	if level >= MaxLevel {
		return MaxLevel, 0
	}
	exp += gain
	for level < MaxLevel {
		need := t.ToNext(level)
		if need <= 0 || exp < need {
			return level, exp
		}
		exp -= need
		level++
	}
	return MaxLevel, 0
}

// ExpLevelWindow is how far apart player and monster levels may be for a hit
// to pay EXP (phase 2 spec 2.4).
const ExpLevelWindow = 10

// ExpEligible reports whether a player of playerLevel earns EXP from a
// monster of monsterLevel: |playerLevel - monsterLevel| <= ExpLevelWindow.
func ExpEligible(playerLevel, monsterLevel int) bool {
	d := playerLevel - monsterLevel
	return d <= ExpLevelWindow && d >= -ExpLevelWindow
}

// ExpShare is the part of a monster's total EXP (gamedata Level.Exp) that
// damage of its maxHP earns: floor(total * damage / maxHP), with damage capped
// at maxHP so a monster never pays more than total (spec 3.4). Integer math
// only. Paying the share of each attacker's summed damage, less what it was
// already paid, keeps the fractions that single hits would lose.
func ExpShare(total int64, maxHP, damage int) int64 {
	if total <= 0 || maxHP <= 0 || damage <= 0 {
		return 0
	}
	return total * int64(min(damage, maxHP)) / int64(maxHP)
}
